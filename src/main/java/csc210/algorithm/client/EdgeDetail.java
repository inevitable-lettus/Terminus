package csc210.algorithm.client;

import com.fasterxml.jackson.annotation.JsonProperty;
import csc210.algorithm.model.EdgeConfiguration;

/**
 * One item of {@code GET /view/edges} — the <em>nested</em> per-edge shape,
 * which is a different serialization of the same edges that
 * {@code /view/topology} returns flat. Both endpoints exist and disagree in
 * shape; this one is richer and paged, and it is the only place
 * {@code demand_vph} appears.
 *
 * <p>Only {@link Traffic#demandVph()} is actually consumed, by step 4.1. The
 * rest is modeled because it is what the endpoint sends and modelling it makes
 * the contract visible.
 */
public record EdgeDetail(
        int id,
        int from,
        int to,
        int reverseTwin,
        Source source,
        Road road,
        Traffic traffic,
        Weather weather,
        EdgeConfiguration control
) {

    /** Where this edge came from in the OpenStreetMap extract it was compiled from. */
    public record Source(long osmWayId, boolean syntheticReverse) {}

    /**
     * The structural facts, matching {@link csc210.algorithm.model.Edge}.
     *
     * @param roadClass sent as {@code "class"}, which cannot be a Java field name
     */
    public record Road(
            @JsonProperty("class") String roadClass,
            int lanes,
            double lengthM,
            double freeSpeedMps,
            double baseCapacityVph
    ) {}

    /**
     * Live traffic on this edge.
     *
     * @param demandVph vehicles per hour the simulation *wants* to put on this
     *        edge at the current virtual time — the quantity step 4.1 reads.
     *        It is generated by DSTNS from building types and hardcoded
     *        rush-hour windows, so it is a synthetic proxy for passenger
     *        demand, not a measurement of one.
     */
    public record Traffic(
            double demandVph,
            double congestion,
            double effectiveSpeedMps,
            double effectiveCapacityVph,
            double meanSpeedMps,
            double occupancy,
            int vehicleCount,
            int haltingCount
    ) {}

    public record Weather(double rainfall, double flood) {}
}
